function t(key, vars){
  let s = LANG[currentLang] && LANG[currentLang][key];
  if(s == null) s = LANG.tr[key];
  if(s == null) return key;
  if(vars) s = s.replace(/\{(\w+)\}/g, (m,k)=> vars[k] != null ? vars[k] : m);
  return s;
}

